package ex09;

public class Resposta {
    int numeroDeRobos, precoPorRobo;
    String fabricanteDaBase, fabricanteDosBracos;

    public int getNumeroDeRobos() {
        return numeroDeRobos;
    }

    public void setNumeroDeRobos(int numeroDeRobos) {
        this.numeroDeRobos = numeroDeRobos;
    }

    public int getPrecoPorRobo() {
        return precoPorRobo;
    }

    public void setPrecoPorRobo(int precoPorRobo) {
        this.precoPorRobo = precoPorRobo;
    }

    public String getFabricanteDaBase() {
        return fabricanteDaBase;
    }

    public void setFabricanteDaBase(String fabricanteDaBase) {
        this.fabricanteDaBase = fabricanteDaBase;
    }

    public String getFabricanteDosBracos() {
        return fabricanteDosBracos;
    }

    public void setFabricanteDosBracos(String fabricanteDosBracos) {
        this.fabricanteDosBracos = fabricanteDosBracos;
    }
}
