package ex08;

public class Dados {
    int numeroDeNomes;
    int idade;

    public Dados(int numeroDeNomes, int idade) {
        this.numeroDeNomes = numeroDeNomes;
        this.idade = idade;
    }

    public int getIdade() {
        return idade;
    }

    public int getNumeroDeNomes() {
        return numeroDeNomes;
    }
}
